// ============================================================
// Companion JSON Schemas (ROK-1954, ROK-1955). `packages/contract/companion/envelope/v1/schema.json`,
// `companion/bg3-save/v1/schema.json` and `companion/device-link/v1/schema.json`
// are GENERATED by these builders —
// run `npm run build -w packages/contract && node packages/contract/scripts/gen-companion-schemas.mjs`.
// The api jest drift guard (`api/src/companion/companion-contract.spec.ts`)
// fails when a committed file differs.
