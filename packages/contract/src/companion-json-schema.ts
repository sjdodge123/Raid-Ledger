/** `$id` of the companion envelope JSON Schema. */
export const COMPANION_ENVELOPE_SCHEMA_ID =
    `https://raid.gamernight.net/contracts/companion/envelope/v${COMPANION_ENVELOPE_VERSION}/schema.json`;

/** `$id` of the `bg3-save` message JSON Schema. */
export const BG3_SAVE_SCHEMA_ID =
    `https://raid.gamernight.net/contracts/companion/bg3-save/v${BG3_SAVE_CONTRACT_VERSION}/schema.json`;

/** Draft-2020-12 INPUT-mode conversion (what the server ACCEPTS); throws on anything unrepresentable. */
function toInputJsonSchema(schema: z.ZodType): Record<string, unknown> {
    const generated: Record<string, unknown> = z.toJSONSchema(schema, {
        target: 'draft-2020-12',
        io: 'input',
        unrepresentable: 'throw',
    });
    return generated;
}

/** The JSON Schema object for the stage-one companion envelope. */
export function buildCompanionEnvelopeJsonSchema(): Record<string, unknown> {
    return {
        ...toInputJsonSchema(CompanionEnvelopeSchema),
        $id: COMPANION_ENVELOPE_SCHEMA_ID,
        title: `RL Companion envelope v${COMPANION_ENVELOPE_VERSION}`,
        description:
            'GENERATED from CompanionEnvelopeSchema (packages/contract/src/companion-envelope.schema.ts) — do not edit by hand. `payload` is opaque here: the server picks the contract message schema from `contract` + `contractVersion` and parses the whole body with it. The server alone rejects a `capturedAt` more than 5 minutes in the future; see CONTRACT.md.',
    };
}

/** The JSON Schema object for one `bg3-save` v1 message. */
export function buildBg3SaveJsonSchema(): Record<string, unknown> {
    return {
        ...toInputJsonSchema(Bg3SaveMessageSchema),
        $id: BG3_SAVE_SCHEMA_ID,
        title: `RL Companion bg3-save message v${BG3_SAVE_CONTRACT_VERSION}`,
        description:
            'GENERATED from Bg3SaveMessageSchema (packages/contract/src/companion-bg3-save.schema.ts) — do not edit by hand. Refinements enforced by the Zod schema but not expressible here: a party member\'s xpLevel ≤ xpTotal; isSummon ⇒ classes is empty; !isSummon ⇒ at least one class; payload.savedAt ≤ capturedAt. The server alone checks the clock; see CONTRACT.md.',
    };
}

/** Exact file contents of `companion/envelope/v1/schema.json` (2-space indent, trailing newline). */
export function serializeCompanionEnvelopeJsonSchema(): string {
    return `${JSON.stringify(buildCompanionEnvelopeJsonSchema(), null, 2)}\n`;
}

/** Exact file contents of `companion/bg3-save/v1/schema.json` (2-space indent, trailing newline). */
export function serializeBg3SaveJsonSchema(): string {
    return `${JSON.stringify(buildBg3SaveJsonSchema(), null, 2)}\n`;
}

// ------------------------------------------------------------
// device-link v1 (ROK-1955). Not a companion-envelope message: this is the
// HTTP surface that mints the device token, so it has no registry entry.
// ------------------------------------------------------------

/** Version of the `companion/device-link` contract folder. */
export const COMPANION_DEVICE_LINK_CONTRACT_VERSION = 1;

/** `$id` of the device-link JSON Schema. */
export const COMPANION_DEVICE_LINK_SCHEMA_ID =
    `https://raid.gamernight.net/contracts/companion/device-link/v${COMPANION_DEVICE_LINK_CONTRACT_VERSION}/schema.json`;

/**
 * Every wire body the companion APP sends or receives, keyed by the name used
 * for its `$defs` entry and as the fixture filename prefix. The web-only
 * approve/Devices routes are Raid Ledger internal and are not listed.
 */
export const COMPANION_DEVICE_LINK_MESSAGES = {
    'start-request': CompanionLinkStartRequestSchema,
    'start-response': CompanionLinkStartResponseSchema,
    'poll-request': CompanionLinkPollRequestSchema,
    'poll-success': CompanionLinkPollSuccessSchema,
    'poll-error': CompanionLinkPollErrorSchema,
    'device-self': CompanionDeviceSelfSchema,
} as const satisfies Record<string, z.ZodType>;

/** One device-link message's draft-2020-12 schema, without its own `$schema` key. */
function toDeviceLinkDef(schema: z.ZodType, io: 'input' | 'output'): Record<string, unknown> {
    const generated: Record<string, unknown> = z.toJSONSchema(schema, {
        target: 'draft-2020-12',
        io,
        unrepresentable: 'throw',
    });
    const { $schema: _drop, ...def } = generated;
    return def;
}

/** Requests are what the server ACCEPTS (input); responses what it SENDS (output). */
function buildDeviceLinkDefs(): Record<string, Record<string, unknown>> {
    const defs: Record<string, Record<string, unknown>> = {};
    for (const [name, schema] of Object.entries(COMPANION_DEVICE_LINK_MESSAGES)) {
        defs[name] = toDeviceLinkDef(schema, name.endsWith('-request') ? 'input' : 'output');
    }
    return defs;
}

/** The JSON Schema object for `companion/device-link/v1` — one `$defs` entry per message. */
export function buildCompanionDeviceLinkJsonSchema(): Record<string, unknown> {
    return {
        $schema: 'https://json-schema.org/draft/2020-12/schema',
        $id: COMPANION_DEVICE_LINK_SCHEMA_ID,
        title: `RL Companion device-link v${COMPANION_DEVICE_LINK_CONTRACT_VERSION}`,
        description:
            'GENERATED from packages/contract/src/companion-devices.schema.ts — do not edit by hand. One $defs entry per HTTP body the companion app sends or receives while linking (start, poll) and checking its token (device-self); the root accepts none of them on purpose. Server-only rules (expiry, slow_down, rate limits, device cap, token handling) are in CONTRACT.md.',
        $defs: buildDeviceLinkDefs(),
        not: {},
    };
}

/** Exact file contents of `companion/device-link/v1/schema.json` (2-space indent, trailing newline). */
export function serializeCompanionDeviceLinkJsonSchema(): string {
    return `${JSON.stringify(buildCompanionDeviceLinkJsonSchema(), null, 2)}\n`;
}
